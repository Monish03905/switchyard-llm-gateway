TASKS_BY_ID = {task.id: task for task in TASKS}
TASKS_BY_PROMPT = {" ".join(task.prompt.lower().split()): task for task in TASKS}
CATEGORIES = sorted({task.category for task in TASKS})


def normalize_prompt(prompt: str) -> str:
    return " ".join((prompt or "").lower().split())


def get_task(task_id: str) -> EvalTask | None:
    return TASKS_BY_ID.get(task_id)


def match_task(prompt: str) -> EvalTask | None:
    return TASKS_BY_PROMPT.get(normalize_prompt(prompt))
